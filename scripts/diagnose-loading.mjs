import { PrismaClient } from "@prisma/client";
import { randomUUID, randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { connectionUrl, sanitizedFailure } from "./database-snapshot.mjs";

const base = "https://request-production-a066.up.railway.app";
const url = new URL(connectionUrl());
url.searchParams.set("connect_timeout", "20");
const db = new PrismaClient({ datasources: { db: { url: url.toString() } }, log: [{ emit: "event", level: "query" }] });
const measurements = [];
const queries = [];
let profiling = false;
let sessionId;
const result = { measuredAt: new Date().toISOString(), source: "Published Railway API; requests originate from the local machine", measurements, queries };
db.$on("query", event => {
  if (profiling) queries.push({ operation: event.query.trim().split(/\s+/)[0], table: event.query.match(/(?:FROM|UPDATE)\s+`[^`]+`\.`([^`]+)`/i)?.[1] ?? "query", ms: event.duration });
});
async function measure(path, cookie) {
  const started = performance.now();
  const response = await fetch(base + path, { cache: "no-store", redirect: "error", signal: AbortSignal.timeout(30_000), headers: cookie ? { cookie } : {} });
  const body = await response.text();
  const metric = { path, status: response.status, ms: Math.round(performance.now() - started) };
  measurements.push(metric);
  console.log(JSON.stringify(metric));
  if (!response.ok) throw new Error(`Diagnostic request failed: ${path} (${response.status})`);
  return body;
}
try {
  const ready = JSON.parse(await measure("/api/v1/health/ready"));
  if (ready.sessionStore !== "tidb") throw new Error("This diagnostic requires the confirmed TiDB session store.");
  await measure("/api/v1/health/live");
  await measure("/api/v1/health/live");
  const admin = await db.user.findFirst({ where: { status: "active", roles: { some: { role: { code: "system_admin" } } } }, select: { id: true } });
  if (!admin) throw new Error("No active administrator is available for the diagnostic.");
  const now = new Date();
  sessionId = randomUUID();
  await db.serverSession.create({ data: { id: sessionId, userId: admin.id, csrfToken: randomUUID(), createdAt: now, lastSeenAt: now, expiresAt: new Date(now.getTime() + 5 * 60_000) } });
  const cookie = `__Host-session=${sessionId}; session=${sessionId}`;
  for (let i = 0; i < 3; i++) {
    const body = JSON.parse(await measure("/api/v1/auth/me", cookie));
    if (body.user?.id !== admin.id) throw new Error("The diagnostic session did not resolve to the expected administrator.");
  }
  for (const path of ["/api/v1/reports/branches", "/api/v1/reports/branches", "/api/v1/warehouse/requests", "/api/v1/warehouse/requests/groups?groupBy=supplier"]) await measure(path, cookie);

  // Count the actual statements generated by the same session/user lookup, using
  // a separate local profile. These durations are not Railway's per-query timings.
  process.env.DATABASE_URL = url.toString();
  process.env.APP_DATABASE_URL = url.toString();
  process.env.NODE_ENV = "test";
  process.env.SESSION_SECRET = randomBytes(32).toString("hex");
  delete process.env.REDIS_URL;
  const { SessionService } = await import("../apps/api/dist/session.service.js");
  const sessions = new SessionService(db);
  profiling = true;
  const started = performance.now();
  await sessions.get(sessionId);
  await db.user.findUnique({ where: { id: admin.id }, select: { id: true, username: true, email: true, status: true, roles: { select: { role: { select: { permissions: { select: { permission: { select: { code: true } } } } } } } } } });
  profiling = false;
  result.localAuthProfile = { statements: queries.length, ms: Math.round(performance.now() - started), scope: "Same Prisma operations as auth/me; measured locally against TiDB, not inside Railway" };
  console.log(JSON.stringify({ localAuthProfile: result.localAuthProfile, queries }));
} catch (error) {
  profiling = false;
  console.error(JSON.stringify(sanitizedFailure(error)));
  result.failed = true;
  process.exitCode = 1;
} finally {
  if (sessionId) {
    await db.serverSession.deleteMany({ where: { id: sessionId } });
    result.diagnosticSessionRemoved = await db.serverSession.count({ where: { id: sessionId } }) === 0;
  }
  await db.$disconnect();
  writeFileSync("evidence/loading-diagnostic.json", JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ diagnosticSessionRemoved: result.diagnosticSessionRemoved ?? true }));
}
